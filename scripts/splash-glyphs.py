"""
Generates components/landing/splash-glyphs.ts: the outlines of "KEI Software"
in Glacial Indifference Regular as SVG paths, so the intro wordmark paints on
the very first frame without waiting for any font.

Run:  python scripts/splash-glyphs.py   (needs fontTools + brotli)
"""
import json
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

ROOT = Path(__file__).resolve().parent.parent
TEXT = "KEI Software"
font = TTFont(ROOT / "app/fonts/GlacialIndifference-Regular.woff2")
upm = font["head"].unitsPerEm
asc, desc = font["hhea"].ascent, font["hhea"].descent  # desc is negative
cmap, glyphs, hmtx = font.getBestCmap(), font.getGlyphSet(), font["hmtx"]

# Same box a 1em line-height text line gets: content area centred in 1em.
top = asc - ((asc - desc) - upm) / 2  # font units above the baseline

out = []
for ch in TEXT:
    name = cmap[ord(ch)]
    adv = hmtx[name][0]
    pen = SVGPathPen(glyphs)
    # flip y and move the baseline down to `top`
    glyphs[name].draw(TransformPen(pen, (1, 0, 0, -1, 0, top)))
    out.append({"ch": ch, "w": round(adv / upm, 4), "d": pen.getCommands()})

ts = (
    "// Generated by scripts/splash-glyphs.py — do not edit by hand.\n"
    "// \"KEI Software\" in Glacial Indifference Regular, 1 unit = 1em/"
    f"{upm}.\n"
    f"export const GLYPH_UPM = {upm}\n"
    f"export const GLYPHS: {{ ch: string; w: number; d: string }}[] = {json.dumps(out)}\n"
)
(ROOT / "components/landing/splash-glyphs.ts").write_text(ts, encoding="utf-8")
print("wrote", len(ts), "bytes")
